					--insert all sectionIDs into table @tblData1 under current categoryID
					INSERT INTO @tblData1(EMAssessmentSectionID)
					SELECT EMAssessmentSectionID 
					FROM tblEMAssessmentSection 
					WHERE EMAssessmentCategoryID = @EMAssessmentCategoryID					
				END
				ELSE
				BEGIN				    
					INSERT INTO @tblData1(EMAssessmentSectionID)
					SELECT EMAssessmentSectionID 
					FROM tblEMAssessmentResultSection A INNER JOIN tblEMAssessmentResultCategory C 
                                  ON A.EMAssessmentResultCategoryID = C.EMAssessmentResultCategoryID  
					              WHERE C.InstrumentID = @InstrumentID and C.EMAssessmentCategoryID = @EMAssessmentCategoryID		
					
					SELECT @EMAssessmentResultCategory = A.EMAssessmentResultCategoryID FROM tblEMAssessmentResultSection A INNER JOIN tblEMAssessmentResultCategory C 
                                  ON A.EMAssessmentResultCategoryID = C.EMAssessmentResultCategoryID  
					              WHERE C.InstrumentID = @InstrumentID and C.EMAssessmentCategoryID = @EMAssessmentCategoryID			 				   
				END	
				
