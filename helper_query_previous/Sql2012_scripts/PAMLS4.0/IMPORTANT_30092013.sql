					  INNER JOIN tblEMAssessmentResultCategory C 
					  ON B.EMAssessmentResultCategoryID = C.EMAssessmentResultCategoryID 
					WHERE C.InstrumentID = @InstrumentID and A.EMAssessmentResultSectionID =@EMAssessmentResultSectionID and EMAssessmentAnswerID IN 
